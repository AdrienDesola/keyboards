#!/usr/bin/env python3
"""Pack a folder of finished one-bit frames into a flipbook clip.

    frames2clip.py <frames_dir> <name> --fps 12 [--out DIR]

The packer tries both codecs of clip.h (bit runs, and zero-run/literal
bytes) and keeps the smaller one.

The frames are PNGs at the final size as the user sees it (portrait, at most
68x140), sorted by filename, dark pixels = ink. Use this when the frames were
drawn or composited elsewhere; vid2clip.py does the same from a video.

Writes <out>/<name>.json for the browser mock and <out>/clip_<name>.c for the
firmware, in the same format as vid2clip.py: the display's own orientation,
run-length bytes (bit 7 value, bits 0-6 run 1-127), each frame XORed with the
previous one.

Needs Pillow.
"""

import argparse
import base64
import json
import os
import sys

from PIL import Image


def load_bits(path):
    im = Image.open(path).convert("L")
    w, h = im.size
    px = im.load()
    return [[1 if px[x, y] < 128 else 0 for x in range(w)] for y in range(h)]


def rotate(bits):
    """Portrait (x,y) -> display image (bx = H-1 - y, by = x), H wide, W tall."""
    h, w = len(bits), len(bits[0])
    img = [[0] * h for _ in range(w)]
    for y in range(h):
        for x in range(w):
            img[x][h - 1 - y] = bits[y][x]
    return img


def pack(img):
    flat = [p for row in img for p in row]
    out = bytearray()
    i = 0
    while i < len(flat):
        v = flat[i]
        n = 1
        while i + n < len(flat) and flat[i + n] == v and n < 127:
            n += 1
        out.append((v << 7) | n)
        i += n
    return bytes(out)


def row_bytes(img):
    out = bytearray()
    for row in img:
        for b in range(0, len(row), 8):
            byte = 0
            for k in range(8):
                if b + k < len(row) and row[b + k]:
                    byte |= 0x80 >> k
            out.append(byte)
    return bytes(out)


def pack_bytes(data):
    """Zero-run / literal: 0x00-0x7f + n+1 literals, 0x80-0xff skips header-0x7f zero bytes."""
    out = bytearray()
    i, n = 0, len(data)
    while i < n:
        if data[i] == 0:
            r = 1
            while i + r < n and data[i + r] == 0 and r < 128:
                r += 1
            out.append(0x7f + r)
            i += r
        else:
            r = 1
            # a literal run ends at two zero bytes in a row (one zero is cheaper inline)
            while i + r < n and r < 128 and not (data[i + r] == 0 and i + r + 1 < n and data[i + r + 1] == 0):
                r += 1
            out.append(r - 1)
            out += data[i:i + r]
            i += r
    return bytes(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("frames")
    ap.add_argument("name")
    ap.add_argument("--fps", type=int, default=12)
    ap.add_argument("--out", default=".")
    a = ap.parse_args()

    files = sorted(os.path.join(a.frames, f) for f in os.listdir(a.frames) if f.endswith(".png"))
    if not files:
        sys.exit("no frames")
    frames = [load_bits(f) for f in files]
    H, W = len(frames[0]), len(frames[0][0])
    if W > 68 or H > 140 or any(len(f) != H or len(f[0]) != W for f in frames):
        sys.exit("frames must share one size, at most 68x140")

    imgs = [rotate(b) for b in frames]
    bits, byts = [], []
    prev = None
    for img in imgs:
        delta = img if prev is None else [[p ^ q for p, q in zip(r1, r2)] for r1, r2 in zip(img, prev)]
        bits.append(pack(delta))
        byts.append(pack_bytes(row_bytes(delta)))
        prev = img
    codec = 1 if sum(map(len, byts)) < sum(map(len, bits)) else 0
    packed = byts if codec else bits
    raw_total = len(imgs) * ((H + 7) // 8) * W
    packed_total = sum(len(p) for p in packed)

    os.makedirs(a.out, exist_ok=True)
    meta = {
        "name": a.name, "fps": a.fps, "w": W, "h": H, "frames": len(imgs),
        "raw_bytes": raw_total, "packed_bytes": packed_total, "codec": codec,
        "source": os.path.basename(os.path.normpath(a.frames)),
        "bits": [base64.b64encode(bytes(
            sum((row[x + k] << (7 - k)) for k in range(8) if x + k < W) for row in fr for x in range(0, W, 8)
        )).decode() for fr in frames],
    }
    with open(os.path.join(a.out, a.name + ".json"), "w") as fh:
        json.dump(meta, fh)

    offs = [0]
    for p in packed:
        offs.append(offs[-1] + len(p))
    with open(os.path.join(a.out, "clip_" + a.name + ".c"), "w") as fh:
        fh.write(f"/* Generated by frames2clip.py from {meta['source']}, {a.fps} fps.\n"
                 f" * {len(imgs)} frames, {packed_total} bytes packed ({raw_total} raw), "
                 f"{'zero-run bytes' if codec else 'bit runs'}. */\n")
        fh.write("#include \"clip.h\"\n\n")
        fh.write(f"static const uint8_t {a.name}_data[] = {{\n")
        for p in packed:
            fh.write("    " + ", ".join(f"0x{b:02x}" for b in p) + ",\n")
        fh.write("};\n\n")
        fh.write(f"static const uint32_t {a.name}_offsets[] = {{\n    " + ", ".join(map(str, offs)) + "\n};\n\n")
        fh.write(f"const struct clip {a.name} = {{\n"
                 f"    .frames = {len(imgs)},\n    .fps = {a.fps},\n    .w = {H},\n    .h = {W},\n"
                 f"    .data = {a.name}_data,\n    .offsets = {a.name}_offsets,\n"
                 f"    .codec = {'CLIP_BYTES' if codec else 'CLIP_BITS'},\n}};\n")

    print(f"{a.name}: {len(imgs)} frames @ {a.fps} fps, {'bytes' if codec else 'bits'} {packed_total} B "
          f"({packed_total / len(imgs):.0f} B/frame, raw {raw_total} B)")


if __name__ == "__main__":
    main()
