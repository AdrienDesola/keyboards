#!/usr/bin/env python3
"""Cut one-bit stills for a theme out of pictures or video frames.

    img2still.py OUT.c NAME=SOURCE[@SECONDS] [NAME=SOURCE...] \
        --crop x,y,w,h --size 68x80 [--mode bayer|thresh] [--thresh 0.5] [--scale nearest|area] [--fit]

SOURCE is an image, or a video with @SECONDS for the frame at that time.
--crop is in source pixels and applies to every still in the call; --size is
the stage as the user sees it (68x140 right, 68x80 left). --fit keeps the crop's
aspect and pads with paper instead of stretching. Writes LVGL indexed
1-bit images in the display's orientation, same polarity as gen_jack.py (data
bit 1 = ink on this board), one lv_img_dsc_t per NAME, plus OUT.png previews.

Needs Pillow, and ffmpeg for video sources.
"""

import argparse
import os
import subprocess
import tempfile

from PIL import Image

BAYER4 = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def load(src, tmp):
    if "@" in src:
        path, t = src.rsplit("@", 1)
        out = os.path.join(tmp, "frame.png")
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", t, "-i", path, "-frames:v", "1", out],
                       check=True)
        return Image.open(out).convert("L")
    return Image.open(src).convert("L")


def to_bits(im, w, h, crop, mode, thresh, scale, fit=False):
    if crop:
        x, y, cw, ch = crop
        im = im.crop((x, y, x + cw, y + ch))
    resample = Image.NEAREST if scale == "nearest" else Image.BOX
    if fit:
        k = min(w / im.width, h / im.height)
        fw, fh = max(1, round(im.width * k)), max(1, round(im.height * k))
        pad = Image.new("L", (w, h), 255)
        pad.paste(im.resize((fw, fh), resample), ((w - fw) // 2, (h - fh) // 2))
        im = pad
    else:
        im = im.resize((w, h), resample)
    px = im.load()
    bits = []
    for yy in range(h):
        row = []
        for xx in range(w):
            v = px[xx, yy] / 255.0
            t = (BAYER4[yy % 4][xx % 4] + 0.5) / 16.0 if mode == "bayer" else thresh
            row.append(1 if v < t else 0)  # 1 = ink
        bits.append(row)
    return bits


def to_c(bits, name):
    h, w = len(bits), len(bits[0])  # portrait, as the user sees it
    bw, bh = h, w                    # display orientation
    stride = (bw + 7) // 8
    data = bytearray(stride * bh)
    for py in range(h):
        for px in range(w):
            if bits[py][px]:
                bx, by = bw - 1 - py, px
                data[by * stride + bx // 8] |= 0x80 >> (bx % 8)
    rows = ["    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    return f"""
static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {name}_map[] = {{
#if CONFIG_NICE_VIEW_SILAKKA_WIDGET_INVERTED
    0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0xff,
#else
    0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff,
#endif
{chr(10).join(rows)}
}};

const lv_img_dsc_t {name} = {{
    .header.cf = LV_IMG_CF_INDEXED_1BIT,
    .header.always_zero = 0,
    .header.reserved = 0,
    .header.w = {bw},
    .header.h = {bh},
    .data_size = sizeof({name}_map),
    .data = {name}_map,
}};
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("stills", nargs="+", help="NAME=SOURCE[@SECONDS]")
    ap.add_argument("--crop")
    ap.add_argument("--size", default="68x140")
    ap.add_argument("--mode", choices=["bayer", "thresh"], default="bayer")
    ap.add_argument("--thresh", type=float, default=0.5)
    ap.add_argument("--scale", choices=["nearest", "area"], default="area")
    ap.add_argument("--fit", action="store_true")
    a = ap.parse_args()
    w, h = (int(v) for v in a.size.lower().split("x"))
    crop = tuple(int(v) for v in a.crop.split(",")) if a.crop else None

    parts = ["/* Generated by img2still.py. */", "", "#include <lvgl.h>", "",
             "#ifndef LV_ATTRIBUTE_MEM_ALIGN", "#define LV_ATTRIBUTE_MEM_ALIGN", "#endif"]
    previews = []
    with tempfile.TemporaryDirectory() as tmp:
        for spec in a.stills:
            name, src = spec.split("=", 1)
            bits = to_bits(load(src, tmp), w, h, crop, a.mode, a.thresh, a.scale, a.fit)
            parts.append(to_c(bits, name))
            p = Image.new("L", (w, h))
            p.putdata([0 if v else 255 for row in bits for v in row])
            previews.append(p)
    with open(a.out, "w") as fh:
        fh.write("\n".join(parts))
    sheet = Image.new("L", (len(previews) * (w * 3 + 6), h * 3), 128)
    for i, p in enumerate(previews):
        sheet.paste(p.resize((w * 3, h * 3), Image.NEAREST), (i * (w * 3 + 6), 0))
    sheet.save(os.path.splitext(a.out)[0] + ".png")
    print(f"{a.out}: {len(previews)} stills at {w}x{h}")


if __name__ == "__main__":
    main()
